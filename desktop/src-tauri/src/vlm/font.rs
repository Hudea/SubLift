#[derive(Clone, Copy, Debug)]
pub struct TextMetrics {
    pub cell_w: u32,
    pub cell_h: u32,
    pub advance: u32,
}

pub fn text_metrics(px_height: u32) -> TextMetrics {
    let cell_h = px_height.max(7);
    let advance = ((cell_h as f32) * 0.58).round().max(5.0) as u32;
    let gap = if cell_h >= 20 { 2 } else { 1 };
    let cell_w = advance.saturating_sub(gap).max(4);
    TextMetrics {
        cell_w,
        cell_h,
        advance,
    }
}

pub fn measure_text_width(text: &str, px_height: u32) -> u32 {
    let count = text.chars().count() as u32;
    if count == 0 {
        return 0;
    }
    let m = text_metrics(px_height);
    count * m.advance - (m.advance - m.cell_w)
}

#[inline]
fn glyph_sample(glyph: &[u8; 7], gx: f32, gy: f32) -> f32 {
    let x0 = gx.floor() as i32;
    let y0 = gy.floor() as i32;
    let fx = gx - (x0 as f32);
    let fy = gy - (y0 as f32);

    let at = |x: i32, y: i32| -> f32 {
        if x < 0 || y < 0 || x >= (GLYPH_W as i32) || y >= (GLYPH_H as i32) {
            return 0.0;
        }
        let bit = 4 - x;
        if (glyph[y as usize] >> bit) & 1 == 1 {
            1.0
        } else {
            0.0
        }
    };

    let c00 = at(x0, y0);
    let c10 = at(x0 + 1, y0);
    let c01 = at(x0, y0 + 1);
    let c11 = at(x0 + 1, y0 + 1);
    let top = c00 * (1.0 - fx) + c10 * fx;
    let bot = c01 * (1.0 - fx) + c11 * fx;
    top * (1.0 - fy) + bot * fy
}

pub fn draw_text_ascii(
    img: &mut RgbImage,
    x: u32,
    y: u32,
    text: &str,
    px_height: u32,
    color: [u8; 3],
) {
    let m = text_metrics(px_height);
    let mut cursor_x = x;

    for ch in text.chars() {
        let code = ch as u32;
        let idx = if (0x20..=0x7E).contains(&code) {
            (code - 0x20) as usize
        } else {
            // '?' fallback for non-ASCII character
            (b'?' - 0x20) as usize
        };
        let glyph = &FONT_5X7[idx];

        if idx != 0 {
            for py in 0..m.cell_h {
                let gy = ((py as f32 + 0.5) * (GLYPH_H as f32) / (m.cell_h as f32)) - 0.5;
                for px in 0..m.cell_w {
                    let gx = ((px as f32 + 0.5) * (GLYPH_W as f32) / (m.cell_w as f32)) - 0.5;
                    let cov = glyph_sample(glyph, gx, gy);
                    // Slight contrast boost keeps strokes crisp on light & dark backgrounds
                    let alpha = ((cov - 0.15) / 0.70).clamp(0.0, 1.0);
                    if alpha > 0.02 {
                        img.put_pixel_blended(cursor_x + px, y + py, color, alpha);
                    }
                }
            }
        }
        cursor_x = cursor_x.saturating_add(m.advance);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_printable_ascii_glyphs_render_without_panicking_and_timestamp_fits_label() {
        let timestamp = "1234.56s - 1236.78s";
        let width_13px = measure_text_width(timestamp, 13);
        assert!(
            width_13px <= 160,
            "timestamp width {width_13px}px must fit inside label_w - 20 = 160px"
        );

        let mut img = RgbImage::new_filled(400, 60, [245, 247, 250]);
        draw_text_ascii(&mut img, 10, 10, "#001", 22, [15, 23, 42]);
        draw_text_ascii(&mut img, 10, 40, timestamp, 13, [100, 116, 139]);

        // Verify pixels changed from background color
        let changed = img
            .data
            .chunks_exact(3)
            .filter(|px| *px != [245, 247, 250])
            .count();
        assert!(changed > 50, "expected rendered glyph pixels, got {changed}");

        // Exercise every printable ASCII character 0x20..=0x7E
        for code in 0x20u8..=0x7Eu8 {
            let mut cell = RgbImage::new_filled(24, 24, [0, 0, 0]);
            let s = String::from(code as char);
            draw_text_ascii(&mut cell, 2, 2, &s, 16, [255, 255, 255]);
            let lit = cell.data.iter().filter(|&&b| b > 0).count();
            if code == b' ' {
                assert_eq!(lit, 0);
            } else {
                assert!(lit > 0, "printable ASCII 0x{code:02X} produced no pixels");
            }
        }
    }
}
